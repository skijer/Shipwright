const MarioPose* MarioPoseTable_Find(const char* linkAnimation) {
    for (size_t index = 0; index < sizeof(kPoses) / sizeof(kPoses[0]); index++) {
        if (strcmp(kPoses[index].linkAnimation, linkAnimation) == 0) {
            return &kPoses[index];
        }
    }
    return NULL;
}
